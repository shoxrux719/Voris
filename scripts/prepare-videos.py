"""Create browser-ready portfolio videos. Requires imageio-ffmpeg."""
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
import hashlib
import argparse
import json
import subprocess
import imageio_ffmpeg

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "public/assets/VD"
OUTPUT = ROOT / "public/assets/videos"
OUTPUT.mkdir(parents=True, exist_ok=True)
FFMPEG = imageio_ffmpeg.get_ffmpeg_exe()
ASSET_MANIFEST = ROOT / "src/data/video-assets.ts"


def prepare(source):
    name = source.stem.lower()
    files = {}
    for width, crf, maxrate in [(1080, 25, "2400k"), (720, 25, "1100k")]:
        target = OUTPUT / f"{name}-{width}.partial.mp4"
        subprocess.run([
            FFMPEG, "-hide_banner", "-loglevel", "error", "-y", "-i", str(source),
            "-map", "0:v:0", "-map", "0:a:0?", "-vf", f"scale={width}:-2:flags=lanczos,fps=30",
            "-c:v", "libx264", "-preset", "slow", "-crf", str(crf),
            "-maxrate", maxrate, "-bufsize", maxrate, "-pix_fmt", "yuv420p",
            "-profile:v", "high", "-level:v", "4.0", "-g", "30", "-threads", "2",
            "-c:a", "aac", "-b:a", "96k", "-ar", "48000", "-ac", "2",
            "-movflags", "+faststart", "-map_metadata", "-1", str(target),
        ], check=True)
        digest = hashlib.sha256(target.read_bytes()).hexdigest()[:12]
        final = OUTPUT / f"{name}-{width}-{digest}.mp4"
        target.replace(final)
        files[width] = final
        print(f"Ready: {final.name} ({final.stat().st_size / 1024 / 1024:.1f} MB)", flush=True)
    subprocess.run([
        FFMPEG, "-hide_banner", "-loglevel", "error", "-y", "-ss", "2", "-i", str(source),
        "-frames:v", "1", "-vf", "scale=540:-2", "-q:v", "3", str(OUTPUT / f"{name}-poster.jpg"),
    ], check=True)
    return {"source": source.name, "sourceBytes": source.stat().st_size,
            "fullHdFile": files[1080].name, "fullHdBytes": files[1080].stat().st_size,
            "hdFile": files[720].name, "hdBytes": files[720].stat().st_size}


def package_stream(item):
    name = Path(item["source"]).stem.lower()
    revision = hashlib.sha256(("hls-fmp4-2s-v1" + item["hdFile"] + item["fullHdFile"]).encode()).hexdigest()[:12]
    folder = OUTPUT / "hls" / f"{name}-{revision}"
    streams = {}
    for width, key in [(720, "hdFile"), (1080, "fullHdFile")]:
        target = folder / str(width)
        target.mkdir(parents=True, exist_ok=True)
        subprocess.run([
            FFMPEG, "-hide_banner", "-loglevel", "error", "-y", "-i", str(OUTPUT / item[key]),
            "-map", "0:v:0", "-map", "0:a:0?", "-c", "copy",
            "-hls_time", "2", "-hls_playlist_type", "vod", "-hls_segment_type", "fmp4",
            "-hls_fmp4_init_filename", "init.mp4", "-hls_flags", "independent_segments",
            "-hls_segment_filename", "segment-%03d.m4s", "index.m3u8",
        ], cwd=target, check=True)
        streams[str(width)] = f"/assets/videos/hls/{folder.name}/{width}/index.m3u8"
    return {**item, "hls": streams}


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--package-only", action="store_true", help="Create HLS from existing MP4 files without re-encoding")
    args = parser.parse_args()
    if args.package_only:
        results = json.loads((OUTPUT / "media.json").read_text(encoding="utf-8"))
    else:
        sources = sorted(p for p in SOURCE.iterdir() if p.suffix.lower() in (".mov", ".mp4"))
        with ThreadPoolExecutor(max_workers=2) as pool:
            results = list(pool.map(prepare, sources))
    results = [package_stream(item) for item in results]
    (OUTPUT / "media.json").write_text(json.dumps(results, indent=2), encoding="utf-8")
    assets = {Path(item["source"]).stem.lower(): {
        "720": f'/assets/videos/{item["hdFile"]}',
        "1080": f'/assets/videos/{item["fullHdFile"]}',
        "hls": item["hls"],
    } for item in results}
    ASSET_MANIFEST.write_text(
        "// Generated by scripts/prepare-videos.py.\nexport const videoAssets = "
        + json.dumps(assets, indent=2) + " as const;\n", encoding="utf-8")
    # Retire only previous renditions after every video and the manifest are ready.
    keep = {item[key] for item in results for key in ("hdFile", "fullHdFile")}
    for item in results:
        stem = Path(item["source"]).stem.lower()
        for width in (720, 1080):
            for old in OUTPUT.glob(f"{stem}-{width}*.mp4"):
                if old.name not in keep:
                    old.unlink()
    print("All portfolio videos prepared.", flush=True)
